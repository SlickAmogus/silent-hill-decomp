/*
 * gpu_xenos.c - the 360 side of the PSX libgpu, replacing gpu_nv2a.c.
 *
 * gpu_xbox.c owns the hardware-agnostic half of the renderer (ordering-table
 * walk, PSX primitive decode, screen transform) and compiles for PPC unchanged.
 * This file is only the hardware end: batch the vertices it produces, map PSX
 * draw state onto Xenos state, and submit.
 *
 * SHADERS ARE EMBEDDED (shaders_embedded.c), compiled from the HLSL in shaders/ with
 * the Xbox 360 XDK's fxc. They were an on-disk asset first, for flexibility;
 * that cost two hardware test runs to "shaders not found" for a pair of blobs
 * under a kilobyte combined, which is a bad trade. A vs.vsu / ps.psu beside the
 * disc image still OVERRIDES the embedded pair, so iterating on shaders does not
 * need an ELF rebuild -- the flexibility is kept, the failure mode is not.
 *
 * A file named "nogpu" beside the disc image keeps Xe down entirely. That
 * matters because Xe_Init takes the framebuffer that libXenon's console draws
 * into in software, so once the GPU is up the on-screen boot text is gone;
 * getting it back should not require a different build.
 */
