#include <string.h>
#include <malloc.h>

#include <xenos/xe.h>
#include <xenos/xenos.h>
#include <xenos/edram.h>
#include <console/console.h>
#include <ppc/cache.h>     /* memdcbf: the fb probe must invalidate before reading */

#include "gpu_nv2a.h"
