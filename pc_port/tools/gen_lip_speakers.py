#!/usr/bin/env python3
"""Emit pc_port/src/pc_lipsync_speakers.c, the speaker of each disc voice line,
from pc_port/tools/lip_speakers.txt.

The game has no such table: a cutscene just plays its XA lines. Each line of
lip_speakers.txt is "<xaIdx> = <MODEL>  # <subtitle>", where MODEL is the
speaking character's model file name (HERO, SIBYL, DARIA, LISA, KAU, AR, ...).
Lines left out fall back to telling male from female by pitch at runtime.

The list was made by pairing each line with its cutscene (gen_xa_subtitles.py),
narrowing the speaker to that map's cast, telling male from female by measured
pitch, and reading the dialogue where two of one sex share a scene.

Run after editing lip_speakers.txt:
    python pc_port/tools/gen_lip_speakers.py
"""
import os, re

root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
src = os.path.join(root, "pc_port/tools/lip_speakers.txt")
dst = os.path.join(root, "pc_port/src/pc_lipsync_speakers.c")
COUNT = 727

who = [None] * COUNT
for n, line in enumerate(open(src, encoding="utf-8"), 1):
    body = line.split("#", 1)[0].strip()
    if not body:
        continue
    m = re.fullmatch(r"(\d+)\s*=\s*([A-Z0-9]+)", body)
    if not m or not 0 < int(m.group(1)) < COUNT:
        raise SystemExit("%s:%d: bad line: %r" % (src, n, line))
    who[int(m.group(1))] = m.group(2)

out = ["/* SPDX-License-Identifier: GPL-3.0-or-later */",
       "/* GENERATED by pc_port/tools/gen_lip_speakers.py from lip_speakers.txt. Do not edit. */",
       '#include "pc_lipsync.h"', "",
       "const char* const g_PcLipSpeaker[PC_LIP_LINES] = {"]
for i in range(COUNT):
    out.append('    %s, /* %d */' % ('"%s"' % who[i] if who[i] else "NULL", i))
out += ["};", ""]
open(dst, "w", encoding="utf-8", newline="\n").write("\n".join(out))
print("%s: %d of %d lines tabled" % (dst, sum(1 for w in who if w), COUNT - 1))
