#!/usr/bin/env python3
"""Mouth-shape tracks for disc voice lines.

    python pc_port/tools/gen_lip_shapes.py TSV_DIR    (lip_shapes.txt from Rhubarb's output, then the C)
    python pc_port/tools/gen_lip_shapes.py            (the C from lip_shapes.txt)

lip_shapes.txt has a line per voice line, "<xaIdx>: <seconds> <shape> ...", with
Rhubarb Lip Sync's shapes A-H and X (rest). They were made by decoding each line
(tools/xa_line.py) and running Rhubarb 1.14 with the line's own text:

    rhubarb -f tsv --extendedShapes GHX -d LINE.txt -o NNN.tsv NNN.wav

Emits pc_port/src/pc_lipsync_shapes.c: per line, its first entry; per entry,
the time in centiseconds and the shape (0..8 = A..H, X).
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
TXT = os.path.join(ROOT, 'pc_port/tools/lip_shapes.txt')
DST = os.path.join(ROOT, 'pc_port/src/pc_lipsync_shapes.c')
COUNT = 727
SHAPES = 'ABCDEFGHX'

if len(sys.argv) > 1:
    rows = []
    for name in sorted(os.listdir(sys.argv[1])):
        m = re.fullmatch(r'(\d+)\.tsv', name)
        if not m:
            continue
        cues = []
        for line in open(os.path.join(sys.argv[1], name), encoding='utf-8'):
            t, s = line.split()
            cues.append('%.2f %s' % (float(t), s))
        rows.append('%d: %s' % (int(m.group(1)), ' '.join(cues)))
    with open(TXT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('# Mouth shapes per disc voice line (Rhubarb Lip Sync A-H, X): see gen_lip_shapes.py.\n')
        f.write('\n'.join(rows) + '\n')
    print('wrote', TXT, len(rows), 'lines')

tracks = {}
for line in open(TXT, encoding='utf-8'):
    if line.startswith('#') or not line.strip():
        continue
    idx, rest = line.split(':', 1)
    v = rest.split()
    tracks[int(idx)] = [(int(round(float(v[i]) * 100)), SHAPES.index(v[i + 1])) for i in range(0, len(v), 2)]

first, at, sid = [], [], []
for i in range(COUNT):
    first.append(len(at))
    for t, s in tracks.get(i, []):
        at.append(t)
        sid.append(s)
first.append(len(at))
assert len(at) < 65536

with open(DST, 'w', encoding='utf-8', newline='\n') as f:
    f.write('/* SPDX-License-Identifier: GPL-3.0-or-later */\n')
    f.write('/* GENERATED by pc_port/tools/gen_lip_shapes.py from lip_shapes.txt. Do not edit. */\n')
    f.write('#include "pc_lipsync.h"\n\n')
    f.write('const uint16_t g_PcLipShapeFirst[PC_LIP_LINES + 1] = {\n')
    for i in range(0, len(first), 16):
        f.write('    ' + ', '.join(str(x) for x in first[i:i + 16]) + ',\n')
    f.write('};\n\nconst uint16_t g_PcLipShapeAt[] = {\n')
    for i in range(0, len(at), 16):
        f.write('    ' + ', '.join(str(x) for x in at[i:i + 16]) + ',\n')
    f.write('};\n\nconst uint8_t g_PcLipShapeId[] = {\n')
    for i in range(0, len(sid), 32):
        f.write('    ' + ', '.join(str(x) for x in sid[i:i + 32]) + ',\n')
    f.write('};\n')
print('wrote', DST, len(tracks), 'lines,', len(at), 'cues')
