def cell(tilemap, col, row, wide):
    w = TILE * (2 if wide else 1)
    return tilemap.crop((col * TILE, row * TILE, col * TILE + w, row * TILE + TILE))


def compose(tilemap, source, wide):
    out = Image.new("RGBA", (TILE * (2 if wide else 1), TILE), (0, 0, 0, 0))
    for col, row in source:
        out.alpha_composite(cell(tilemap, col, row, wide))
    return out


def enter(tilemap, dark):
    off = 8 if dark else 0
    bottom = cell(tilemap, 32, 3 + off, True).copy()
    back = cell(tilemap, 32, 1 + off, True)
    outline = back.getpixel((3, 1))
    top = 0
    while back.getpixel((3, top)) in ((0, 0, 0, 0), outline):
        top += 1
    for y in range(top):
        for x in range(2 * TILE):
            bottom.putpixel((x, y), back.getpixel((x, y)))
    return bottom


def glyph_image(tilemap, source, wide, dark):
    if source == "ENTER":
        return enter(tilemap, dark)
    return compose(tilemap, source, wide)


def pack():
    placed = []
    col = row = 0
    for name, light, dark, wide in GLYPHS:
        span = 2 if wide else 1
        if col + span > ATLAS_COLS:
            col = 0
            row += 1
        placed.append((name, light, dark, wide, col, row))
        col += span
        if col >= ATLAS_COLS:
            col = 0
            row += 1
    return placed


def check(placed, atlas):
    used = set()
    names = set()
    for name, light, dark, wide, col, row in placed:
        if name in names:
            sys.exit("duplicate glyph " + name)
        names.add(name)
        if row >= ATLAS_ROWS:
            sys.exit("atlas overflow at " + name)
        span = 2 if wide else 1
        for s in range(span):
            for variant in (0, ATLAS_COLS):
                c = col + s + variant
                if (c, row) in used:
                    sys.exit("cell shared at " + name)
                used.add((c, row))
        for variant in (0, ATLAS_COLS):
            x0 = (col + variant) * TILE
            region = atlas.crop((x0, row * TILE, x0 + span * TILE, row * TILE + TILE))
            if region.getchannel("A").getbbox() is None:
                sys.exit("empty glyph %s (%s)" % (name, "dark" if variant else "light"))


def build():
    tilemap = Image.open(TILEMAP).convert("RGBA")
    placed = pack()
    atlas = Image.new("RGBA", (ATLAS_COLS * 2 * TILE, ATLAS_ROWS * TILE), (0, 0, 0, 0))
    for name, light, dark, wide, col, row in placed:
        atlas.paste(glyph_image(tilemap, light, wide, False), (col * TILE, row * TILE))
        atlas.paste(glyph_image(tilemap, dark, wide, True), ((col + ATLAS_COLS) * TILE, row * TILE))
    check(placed, atlas)
    return placed, atlas


def write_outputs(placed, atlas):
    os.makedirs(os.path.dirname(OUT_PNG), exist_ok=True)
    atlas.save(OUT_PNG)
    shutil.copyfile(LICENSE_SRC, OUT_LICENSE)

    with open(OUT_IDS, "w", newline="\n") as f:
        f.write(HEADER)
        f.write("#ifndef PC_INPUT_GLYPHS_IDS_H\n#define PC_INPUT_GLYPHS_IDS_H\n\n")
        f.write("enum e_InputGlyph {\n")
        for name, *_ in placed:
            f.write("    %s,\n" % name)
        f.write("    IG_COUNT\n};\n\n#endif\n")

    with open(OUT_INC, "w", newline="\n") as f:
        f.write(HEADER)
        f.write("static const struct { unsigned char col, row, wide; } s_igAtlas[IG_COUNT] = {\n")
        for name, light, dark, wide, col, row in placed:
            f.write("    [%s] = { %d, %d, %d },\n" % (name, col, row, 1 if wide else 0))
        f.write("};\n")


def preview(placed, atlas, path):
    sc = 3
    pad = 6
    label_w = 150
    cols = 4
    entry_w = label_w + 2 * (2 * TILE * sc) + 3 * pad
    entry_h = TILE * sc + pad
    rows = (len(placed) + cols - 1) // cols
    img = Image.new("RGBA", (cols * entry_w, rows * entry_h + pad), (70, 80, 100, 255))
    d = ImageDraw.Draw(img)
    for i, (name, light, dark, wide, col, row) in enumerate(placed):
        ex = (i % cols) * entry_w
        ey = (i // cols) * entry_h + pad
        span = (2 if wide else 1) * TILE
        d.text((ex + pad, ey + 16), name[3:], fill="white")
        for v, off in enumerate((0, ATLAS_COLS)):
            c = atlas.crop(((col + off) * TILE, row * TILE, (col + off) * TILE + span, row * TILE + TILE))
            c = c.resize((span * sc, TILE * sc), Image.NEAREST)
            x = ex + label_w + v * (2 * TILE * sc + pad)
            img.alpha_composite(c, (x, ey))
    img.convert("RGB").save(path)


def main():
    placed, atlas = build()
    if "--preview" in sys.argv:
        i = sys.argv.index("--preview")
        if i + 1 >= len(sys.argv):
            sys.exit("usage: build_input_glyphs.py [--preview <out.png>]")
        preview(placed, atlas, sys.argv[i + 1])
        return
    write_outputs(placed, atlas)


if __name__ == "__main__":
    main()
